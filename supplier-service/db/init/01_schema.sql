-- Applied by the official postgres:17 image on first start
-- (/docker-entrypoint-initdb.d) and by Testcontainers the same way.

CREATE EXTENSION IF NOT EXISTS cube;
CREATE EXTENSION IF NOT EXISTS earthdistance;

CREATE TABLE public."Supplier_Database" (
  "Name"                 text                     NOT NULL,
  "Type"                 text                     NOT NULL,
  "Building"             text                     NOT NULL,
  "Floor"                bigint                   DEFAULT 1,
  "Location Description" text                     DEFAULT '',
  "Latitude"             numeric(9,6)             NOT NULL,
  "Longitude"            numeric(9,6)             NOT NULL,
  "StartingTime"         text                     DEFAULT 'NA',
  "ClosingTime"          text                     DEFAULT 'NA',
  "ImageURL"             text,
  id                     bigint                   GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  deleted_at             timestamptz,
  created_at             timestamptz              NOT NULL DEFAULT now(),
  updated_at             timestamptz(3)           NOT NULL DEFAULT now(),
  CONSTRAINT "Supplier_Database_pkey" PRIMARY KEY (id),
  CONSTRAINT lat_range CHECK (("Latitude" >= -90) AND ("Latitude" <= 90)),
  CONSTRAINT lng_range CHECK (("Longitude" >= -180) AND ("Longitude" <= 180)),
  CONSTRAINT name_length CHECK ((length(btrim("Name")) >= 1) AND (length(btrim("Name")) <= 100))
);

ALTER TABLE public."Supplier_Database"
  ADD COLUMN fts tsvector
  GENERATED ALWAYS AS (
    setweight(to_tsvector('english', coalesce("Name", '')), 'A')
    || setweight(to_tsvector('english', coalesce("Building", '')), 'B')
    || setweight(to_tsvector('english', coalesce("Location Description", '')), 'B')
  ) STORED;

CREATE INDEX supplier_fts_idx ON public."Supplier_Database" USING gin (fts);

-- Active names only. A btree on deleted_at itself is not useful: almost every
-- query is `deleted_at IS NULL`, which that index does not serve.
CREATE UNIQUE INDEX unique_active_supplier_name
  ON public."Supplier_Database" ("Name")
  WHERE deleted_at IS NULL;

-- Bounding-box probe for earth_distance (metres). Exact filter stays in SQL.
CREATE INDEX idx_supplier_earth
  ON public."Supplier_Database"
  USING gist (ll_to_earth("Latitude"::float8, "Longitude"::float8));

COMMENT ON TABLE public."Supplier_Database" IS
  'Campus suppliers: unique id, location, building, floor, description';
